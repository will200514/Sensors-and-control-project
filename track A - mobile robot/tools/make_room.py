"""Build the MuJoCo scenes from src/config.py:  python tools/make_room.py
assets/room.xml   5 x 5 m room, walls, the 13 ArUco markers in config.MARKERS, obstacle slots, the robot
assets/calib.xml  the robot and a checkerboard, for tools/calibrate_camera.py
"""
import sys
from pathlib import Path
import numpy as np
import cv2

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src import config as C  # noqa: E402

N_OBST = 8   # obstacle slots, moved to each trial's layout by MujocoWorld
# Same ArUco dictionary as the Week 3 tutorial
ARUCO = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_4X4_50)


def yaw_quat(a):
    return f"{np.cos(a / 2):.5f} 0 0 {np.sin(a / 2):.5f}"


def marker(j, x, y, facing):
    #ArUco marker j as black tiles on a white square, centred at camera height, facing into the room.
    bits = cv2.aruco.generateImageMarker(ARUCO, j, 6)       # 6x6 cells: 4x4 code + black border
    cell = C.MARKER_L / 6
    n = np.array([np.cos(facing), np.sin(facing)])          # out of the wall
    t = np.array([-n[1], n[0]])                             # along the wall (viewer's right)
    q, z = yaw_quat(facing), C.CAM_HEIGHT
    p = np.array([x, y]) + 0.002 * n
    g = [f'<geom type="box" size="0.001 {4*cell:.4f} {4*cell:.4f}" pos="{p[0]:.4f} {p[1]:.4f} {z}" quat="{q}" rgba="1 1 1 1" contype="0" conaffinity="0"/>']
    for r in range(6):
        for k in range(6):
            if bits[r, k] < 128:
                p = np.array([x, y]) + 0.004 * n + (k - 2.5) * cell * t
                g.append(f'<geom type="box" size="0.001 {cell/2:.4f} {cell/2:.4f}" pos="{p[0]:.4f} {p[1]:.4f} '
                         f'{z + (2.5 - r) * cell:.4f}" quat="{q}" rgba="0 0 0 1" contype="0" conaffinity="0"/>')
    return g


def room_xml():
    geoms = [  # walls (contact group 2, like the robot body)
        '<geom type="box" size="2.6 0.05 0.35" pos="2.5 -0.05 0.35" rgba=".86 .86 .82 1" contype="2" conaffinity="2"/>',
        '<geom type="box" size="2.6 0.05 0.35" pos="2.5 5.05 0.35" rgba=".86 .86 .82 1" contype="2" conaffinity="2"/>',
        '<geom type="box" size="0.05 2.6 0.35" pos="-0.05 2.5 0.35" rgba=".86 .86 .82 1" contype="2" conaffinity="2"/>',
        '<geom type="box" size="0.05 2.6 0.35" pos="5.05 2.5 0.35" rgba=".86 .86 .82 1" contype="2" conaffinity="2"/>',
    ]
    for j, (x, y, facing) in enumerate(C.MARKERS):
        geoms += marker(j, x, y, facing)
    # green charging station under the dock marker (visual only)
    dx, dy, _ = C.DOCK_MARKER
    geoms.append(f'<geom type="box" size="0.04 0.12 0.03" pos="{dx - 0.04} {dy} 0.03" rgba="0.1 0.6 0.25 1" contype="0" conaffinity="0"/>')
    obst = "\n".join(f'    <body name="obst{i}" pos="0 0 -5"><geom name="obst{i}" type="cylinder" size="0.2 0.2" pos="0 0 0.2" '
                     f'rgba="0.55 0.35 0.2 1" contype="2" conaffinity="2"/></body>' for i in range(N_OBST))
    body = "\n".join("    " + g for g in geoms)
    return f'''<mujoco model="track_a_room">
  <!-- Generated by tools/make_room.py -->
  <include file="robotis_tb3/turtlebot3_burger_a4.xml"/>
  <option timestep="0.002"/>
  <visual>
    <headlight diffuse="0.6 0.6 0.6" ambient="0.35 0.35 0.35" specular="0 0 0"/>
    <global offwidth="1920" offheight="1080"/>
  </visual>
  <asset>
    <texture type="skybox" builtin="gradient" rgb1="0.75 0.8 0.85" rgb2="0.35 0.4 0.45" width="512" height="3072"/>
    <texture type="2d" name="floor" builtin="checker" rgb1="0.46 0.46 0.46" rgb2="0.41 0.41 0.41" width="300" height="300"/>
    <material name="floor" texture="floor" texrepeat="10 10"/>
  </asset>
  <worldbody>
    <light pos="2.5 2.5 4" dir="0 0 -1" directional="true" diffuse="0.5 0.5 0.5" castshadow="false"/>
    <geom name="floor" type="plane" size="2.5 2.5 0.05" pos="2.5 2.5 0" material="floor"/>
    <!-- overview camera for demos; the robot's own camera is "cam" in the robot file -->
    <camera name="overview" pos="2.5 -1.0 5.2" xyaxes="1 0 0 0 0.837 0.547" fovy="52"/>
{body}
{obst}
  </worldbody>
</mujoco>
'''


def calib_xml(gx=9, gy=6, sq=0.025):
    """Checkerboard with gx x gy inner corners (Week 3 tutorial board) on a movable (mocap) body."""
    tiles = [f'<geom type="box" size="0.001 {(gx + 3) * sq / 2} {(gy + 3) * sq / 2}" pos="-0.002 0 0" rgba="1 1 1 1" contype="0" conaffinity="0"/>']
    for a in range(gx + 1):
        for b in range(gy + 1):
            if (a + b) % 2 == 0:
                tiles.append(f'<geom type="box" size="0.001 {sq / 2} {sq / 2}" pos="0 {(a - gx / 2) * sq:.4f} '
                             f'{(gy / 2 - b) * sq:.4f}" rgba="0 0 0 1" contype="0" conaffinity="0"/>')
    t = "\n".join("      " + g for g in tiles)
    return f'''<mujoco model="track_a_calib">
  <!-- Generated by tools/make_room.py -->
  <include file="robotis_tb3/turtlebot3_burger_a4.xml"/>
  <asset>
    <texture type="skybox" builtin="gradient" rgb1="0.55 0.55 0.55" rgb2="0.3 0.3 0.3" width="256" height="1536"/>
  </asset>
  <worldbody>
    <body name="board" mocap="true" pos="0.6 0 {C.CAM_HEIGHT}" quat="0 0 0 1">
{t}
    </body>
  </worldbody>
</mujoco>
'''


if __name__ == "__main__":
    (ROOT / "assets" / "room.xml").write_text(room_xml())
    (ROOT / "assets" / "calib.xml").write_text(calib_xml())
    print("wrote assets/room.xml and assets/calib.xml")
